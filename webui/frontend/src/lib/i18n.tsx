type Translate = (k: string, vars?: Record<string, string | number>) => string

const I18nCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Translate }>({
  lang: "zh-Hans",
  setLang: () => {},
  t: (k) => k,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const v = localStorage.getItem(LANG_KEY)
    return v === "zh-Hant" || v === "en" ? v : "zh-Hans"
  })
  useEffect(() => {
    localStorage.setItem(LANG_KEY, lang)
    document.documentElement.lang = lang === "zh-Hans" ? "zh-CN" : lang === "zh-Hant" ? "zh-TW" : "en"
  }, [lang])
  const t: Translate = (k, vars) => {
    let s = dict[lang][k] ?? dict["zh-Hans"][k] ?? k
    if (vars) for (const [p, v] of Object.entries(vars)) s = s.split(`{${p}}`).join(String(v))
    return s
  }
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>
}

export function useI18n() {
  return useContext(I18nCtx)
}

export type { Translate }
